import { cn } from "@/lib/utils";

/**
 * The site's colour atmosphere: a four-pool mesh, floating light clouds,
 * sweeping beams and twinkling dust.
 *
 * The navy is the material; this layer is the lighting. Everything here is
 * decorative — the wrapper is aria-hidden and pointer-events-none, and the
 * component is a server component, so it adds nothing to the client bundle.
 *
 * Two rules keep it from becoming noise:
 *
 * 1. Hues come from the design tokens, and only from the palette's lights
 *    (violet, cyan, champagne, ice). Because the orbs and beams are composited
 *    with `mix-blend-mode: screen`, overlaps *add* — which is where the colours
 *    between two lights come from.
 * 2. Nothing animates a layout property. The mesh breathes with a transform
 *    and an opacity, the orbs drift on transforms, the beams translate across
 *    the viewport, the grid translates by exactly one tile. All of it is
 *    composited, and the global prefers-reduced-motion rule stops every one of
 *    them at once.
 *
 * The dust is generated by a seeded LCG, so positions are identical on the
 * server and in the browser: no hydration mismatch and no layout shift.
 */

interface Orb {
  id: string;
  /** Placement and size utilities, kept explicit so the layout is readable. */
  className: string;
  /** A palette token reference, never a literal colour. */
  color: string;
  opacity: string;
  /** Seconds; each orb runs on its own tempo so the field never moves as one. */
  duration: string;
  delay: string;
}

