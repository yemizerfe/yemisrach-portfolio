/** The dust borrows the same lights as the orbs, so it never introduces a hue. */
const sparkColors = [
  "var(--color-accent-cyan)",
  "var(--color-accent-violet)",
  "var(--color-accent)",
  "var(--color-accent-ice)",
];

/**
 * Seeded scatter for the dust. A plain LCG rather than Math.random(), because
 * the pattern has to be identical on every render.
 */
function scatter(count: number, seed: number) {
  let state = seed;
  const next = () => {
    state = (state * 1664525 + 1013904223) % 4294967296;
    return state / 4294967296;
  };

  return Array.from({ length: count }, (_, index) => ({
    id: index,
    left: Number((next() * 98).toFixed(2)),
    top: Number((next() * 94).toFixed(2)),
    size: Number((1.5 + next() * 2.5).toFixed(2)),
    duration: Number((5 + next() * 7).toFixed(1)),
    delay: Number((next() * 9).toFixed(1)),
    opacity: Number((0.4 + next() * 0.5).toFixed(2)),
    color: sparkColors[Math.floor(next() * sparkColors.length)],
  }));
}

/** Fixed seed: the pattern is part of the design, not a random effect. */
const sparks = scatter(26, 19880213);

interface MeshBackdropProps {
  className?: string;
  /** The colour mesh is expensive to composite twice, so it can be dropped. */
  showMesh?: boolean;
  /** Twinkling dust can be dropped where a section already has texture. */
  showSparks?: boolean;
}

export function MeshBackdrop({
  className,
  showMesh = true,
  showSparks = true,
}: MeshBackdropProps) {
  return (
    <div
      aria-hidden="true"
      className={cn(
        "pointer-events-none absolute inset-0 overflow-hidden",
        className,
      )}
    >
      {/* Layer 1 — the colour field itself. */}
      {showMesh ? <div className="mesh-field" /> : null}

      {/* Layer 2 — a hairline grid panning on a 72px pitch, faded out at the
          edges so it reads as texture rather than as a table. */}
      <div className="grid-veil" />

      {/* Layer 3 — light beams crossing the upper page. */}
      <div className="beam-layer">
        {beams.map((beam) => (
          <span
            key={beam.id}
            className="beam"
            style={
              {
                "--beam-color": beam.color,
                "--beam-duration": beam.duration,
                "--beam-delay": beam.delay,
              } as CSSProperties
            }
          />
        ))}
      </div>

      {/* Layer 4 — floating light clouds. */}
      {orbs.map((orb) => (
        <span
          key={orb.id}
          className={cn("orb", orb.className)}
          style={
            {
              "--orb-color": orb.color,
              "--orb-opacity": orb.opacity,
              "--orb-duration": orb.duration,
              "--orb-delay": orb.delay,
            } as CSSProperties
          }
        />
      ))}

      {/* Layer 5 — dust. Small, few, and only ever half-visible. */}
      {showSparks
        ? sparks.map((spark) => (
            <span
              key={`spark-${spark.id}`}
              className="spark"
              style={
                {
                  left: `${spark.left}%`,
                  top: `${spark.top}%`,
                  width: `${spark.size}px`,
                  height: `${spark.size}px`,
                  "--spark-color": spark.color,
                  "--spark-opacity": spark.opacity,
                  "--spark-duration": `${spark.duration}s`,
                  "--spark-delay": `${spark.delay}s`,
                } as CSSProperties
              }
            />
          ))
        : null}
    </div>
  );
}
